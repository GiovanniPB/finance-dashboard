  c.id, a.id, s.amount::numeric,
  case when a.kind in ('revenue','financial_income') then 'inflow'::transaction_direction
       when a.kind = 'partner_bonus' and s.raw_sign = '+' then 'inflow'::transaction_direction
       else 'outflow'::transaction_direction end,
  'settled'::transaction_status,
  make_date(s.year::int, s.month::int, 15),
  make_date(s.year::int, s.month::int, 15),
  s.label || ' · ' || to_char(make_date(s.year::int, s.month::int, 1), 'TMMon/YYYY'),
  (select id from auth.users order by created_at limit 1),
  jsonb_build_object('source','spreadsheet_2025','reference_month', make_date(s.year::int, s.month::int, 1))
from seed s
join companies c on c.trade_name = s.company
join chart_of_accounts a on a.company_id = c.id and a.code = s.code;
